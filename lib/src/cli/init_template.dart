import '../config/config_model.dart';
import '../discovery/project_files.dart';
import '../validators/android_project.dart';

/// A brand detected while scaffolding a configuration.
class DetectedBrand {
  /// Creates a detected brand.
  const DetectedBrand({
    required this.id,
    this.applicationId,
    this.appName,
    this.launcherIcon,
    this.logo,
  });

  /// Brand ID.
  final String id;

  /// Literal applicationId from the product flavor.
  final String? applicationId;

  /// Literal app name from a flavor `resValue`.
  final String? appName;

  /// Candidate launcher icon path.
  final String? launcherIcon;

  /// Candidate logo path.
  final String? logo;
}

/// What `init` discovered about the project.
class InitDetection {
  /// Creates a detection result.
  const InitDetection({
    required this.projectName,
    required this.brands,
    required this.arbDirectory,
    required this.locales,
    required this.notes,
  });

  /// `pubspec.yaml` name.
  final String projectName;

  /// Detected brands (may be empty).
  final List<DetectedBrand> brands;

  /// Detected ARB directory.
  final String? arbDirectory;

  /// Locales with an `app_<locale>.arb` file.
  final List<String> locales;

  /// Human-readable notes about what was detected.
  final List<String> notes;

  /// Inspects [files] without modifying anything.
  static InitDetection detect(ProjectFiles files, String projectName) {
    final notes = <String>[];

    String? arbDirectory;
    final l10n = files.readText('l10n.yaml');
    final arbDir = l10n == null
        ? null
        : RegExp(r'^arb-dir:\s*(\S+)', multiLine: true).firstMatch(l10n)?[1];
    if (arbDir != null && files.directoryExists(arbDir)) {
      arbDirectory = arbDir;
    } else if (files.directoryExists('lib/l10n')) {
      arbDirectory = 'lib/l10n';
    }
    final locales = <String>[];
    if (arbDirectory != null) {
      final pattern = RegExp(
        '^${RegExp.escape(arbDirectory)}/app_([A-Za-z0-9_]+)\\.arb\$',
      );
      for (final file in files.all) {
        final match = pattern.firstMatch(file);
        if (match != null) locales.add(match[1]!);
      }
      notes.add(
        'ARB directory $arbDirectory'
        '${locales.isEmpty ? '' : ' with locales ${locales.join(', ')}'}',
      );
    }

    final brands = <String, DetectedBrand>{};
    final android = AndroidProject.load(files, const AndroidPlatformConfig());
    if (android != null && android.gradle.flavors.isNotEmpty) {
      for (final flavor in android.gradle.flavors.values) {
        brands[flavor.name] = DetectedBrand(
          id: flavor.name,
          applicationId: flavor.properties['applicationId']?.literal,
          // Same resolution as app_name_mismatch: manifest label through
          // resValue, strings.xml or manifestPlaceholders.
          appName: android.appNameFor(flavor.name).value,
        );
      }
      notes.add(
        'Android product flavors: ${android.gradle.flavors.keys.join(', ')}',
      );
    }

    const brandsRoot = 'assets/brands';
    if (files.directoryExists(brandsRoot)) {
      final directories =
          files.all
              .where((f) => f.startsWith('$brandsRoot/'))
              .map((f) => f.substring(brandsRoot.length + 1).split('/').first)
              .toSet()
              .toList()
            ..sort();
      for (final id in directories) {
        if (!RegExp(r'^[A-Za-z0-9][A-Za-z0-9_-]*$').hasMatch(id)) continue;
        final assets = files.all
            .where((f) => f.startsWith('$brandsRoot/$id/'))
            .toList();
        String? find(RegExp pattern) => assets
            .where((f) => pattern.hasMatch(p.posix.basename(f).toLowerCase()))
            .firstOrNull;
        final existing = brands[id];
        brands[id] = DetectedBrand(
          id: id,
          applicationId: existing?.applicationId,
          appName: existing?.appName,
          launcherIcon: find(RegExp(r'icon.*\.png$')),
          logo: find(RegExp(r'^logo.*\.(png|svg|webp|jpg)$')),
        );
      }
      notes.add(
        'Brand asset folders under $brandsRoot: ${directories.join(', ')}',
      );
    }

    return InitDetection(
      projectName: projectName,
      brands: brands.values.toList(),
      arbDirectory: arbDirectory,
      locales: locales,
      notes: notes,
    );
  }
}

/// Renders a commented `.brandguard.yaml` from [detection].
String renderInitConfig(InitDetection detection) {
  final out = StringBuffer()
    ..writeln('# BrandGuard configuration.')
    ..writeln('# Reference: see the "Configuration reference" section of the')
    ..writeln(
      '# brandguard_flutter README. Paths are relative to project.root.',
    )
    ..writeln('# Generated by `brandguard init`; review every value below.')
    ..writeln()
    ..writeln('version: 1')
    ..writeln()
    ..writeln('project:')
    ..writeln('  name: ${_quote(detection.projectName)}')
    ..writeln('  root: .')
    ..writeln()
    ..writeln('# Brand fields every brand must define (rule')
    ..writeln('# missing_brand_configuration). Remove entries you do not need.')
    ..writeln('requirements:')
    ..writeln('  brand_fields:')
    ..writeln('    - name')
    ..writeln('    - app_name')
    ..writeln('    - application_id')
    ..writeln('    - environment')
    ..writeln('    - assets.launcher_icon')
    ..writeln('    - assets.logo');
  if (detection.arbDirectory != null) out.writeln('    - required_locales');
  out
    ..writeln()
    ..writeln('defaults:')
    ..writeln('  # Used by brands that do not set `environment`.')
    ..writeln('  environment: production')
    ..writeln()
    ..writeln('assets:')
    ..writeln('  # Existing assets must be listed under `flutter: assets:`.')
    ..writeln('  require_declaration: true')
    ..writeln(
      '  # Asset kinds used only at build time (no declaration needed).',
    )
    ..writeln('  declaration_exempt: [launcher_icon]')
    ..writeln(
      '  # Convention: assets/brands/<brand id>/ belongs to that brand.',
    )
    ..writeln('  brands_root: assets/brands')
    ..writeln('  isolation:')
    ..writeln('    shared_paths: []        # globs brands may share')
    ..writeln('    compare_content: true   # flag byte-identical brand assets')
    ..writeln('    path_heuristics: true   # flag paths naming another brand')
    ..writeln();
  if (detection.arbDirectory != null) {
    out
      ..writeln('localization:')
      ..writeln('  arb_directory: ${detection.arbDirectory}')
      ..writeln("  file_pattern: 'app_{locale}.arb'")
      ..writeln(
        '  base_locale: '
        '${detection.locales.contains('en') || detection.locales.isEmpty ? 'en' : detection.locales.first}',
      )
      ..writeln('  required_locales: [${detection.locales.join(', ')}]')
      ..writeln('  allow_empty_translations: false')
      ..writeln();
  } else {
    out
      ..writeln('localization:')
      ..writeln('  # No ARB files were found. Set arb_directory and')
      ..writeln('  # required_locales if the project uses gen-l10n.')
      ..writeln('  enabled: false')
      ..writeln();
  }
  out
    ..writeln('environments:')
    ..writeln('  production:')
    ..writeln(
      '    # Files scanned for URLs; {brand} is replaced by the brand ID.',
    )
    ..writeln('    # Example: - config/{brand}/production.json')
    ..writeln('    files: []')
    ..writeln('    # Substrings forbidden in URL hosts of production files.')
    ..writeln('    forbidden_url_patterns: [staging, dev-api]')
    ..writeln('    forbidden_hosts: []')
    ..writeln('    allowed_hosts: []')
    ..writeln('    block_loopback: true   # localhost, 127.0.0.1, 10.0.2.2')
    ..writeln(
      '    heuristics: true       # warn on hosts like api.dev.example.com',
    )
    ..writeln('  staging:')
    ..writeln('    files: []')
    ..writeln('    forbidden_url_patterns: []')
    ..writeln()
    ..writeln('platforms:')
    ..writeln('  android:')
    ..writeln('    enabled: true')
    ..writeln('  ios:')
    ..writeln('    enabled: true')
    ..writeln('    target: Runner')
    ..writeln()
    ..writeln(
      '# Per-rule overrides: `enabled` and `severity` (error|warning|info).',
    )
    ..writeln('rules:')
    ..writeln('  brand_asset_leakage:')
    ..writeln('    severity: warning')
    ..writeln('  suspicious_environment_url:')
    ..writeln('    severity: warning')
    ..writeln()
    ..writeln('brands:');

  final brands = detection.brands.isEmpty
      ? const [DetectedBrand(id: 'my_brand')]
      : detection.brands;
  if (detection.brands.isEmpty) {
    out.writeln(
      '  # No brands were detected. Replace this example with your brands.',
    );
  }
  for (final brand in brands) {
    out
      ..writeln('  - id: ${brand.id}')
      ..writeln('    name: ${_quote(_titleCase(brand.id))}')
      ..writeln(
        '    app_name: ${_quote(brand.appName ?? _titleCase(brand.id))}',
      )
      ..writeln(
        '    application_id: '
        '${brand.applicationId ?? 'com.example.${brand.id.replaceAll('-', '_')}'}',
      )
      ..writeln(
        '    # flavor: ${brand.id}   # Android flavor / iOS config suffix',
      )
      ..writeln('    assets:')
      ..writeln(
        '      launcher_icon: '
        '${brand.launcherIcon ?? 'assets/brands/${brand.id}/app_icon.png'}',
      )
      ..writeln(
        '      logo: ${brand.logo ?? 'assets/brands/${brand.id}/logo.png'}',
      );
  }
  return out.toString();
}

String _titleCase(String id) => id
    .split(RegExp(r'[_-]'))
    .where((w) => w.isNotEmpty)
    .map((w) => '${w[0].toUpperCase()}${w.substring(1)}')
    .join(' ');

String _quote(String value) => "'${value.replaceAll("'", "''")}'";
